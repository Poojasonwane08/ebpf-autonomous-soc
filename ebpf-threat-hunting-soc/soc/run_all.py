"""Run the complete SOC in ONE Python process (no Docker, no Kafka needed).

    python -m soc.run_all            # then open http://localhost:8080

Uses the in-memory bus; every service runs in its own thread exactly as it
would in its own container.
"""
from __future__ import annotations

import argparse
import logging

from . import config, dashboard, detector, normalizer, simulator, soar
from .bus import MemoryBus, create_bus


def start_pipeline(eps: float | None = None, serve: bool = True, bus_kind: str = "memory",
                   port: int | None = None):
    bus = MemoryBus() if bus_kind == "memory" else create_bus(bus_kind)
    state = dashboard.run(bus)
    norm = normalizer.run(bus)

    live = config.SENSOR_MODE == "tetragon"
    baseline = None
    if not live:
        # Train the anomaly model on a benign baseline generated by the simulator.
        baseline_sim = simulator.FleetSimulator(None, seed=7)
        baseline = [e for e in (norm.normalize(r) for r in baseline_sim.generate_baseline(3000)) if e]
    engine = detector.run(bus, baseline=baseline)      # live mode learns the baseline online
    soar_engine = soar.run(bus)
    if live:
        from . import tetragon_sensor
        sim = tetragon_sensor.run(bus)
    else:
        sim = simulator.run(bus, eps=eps)
    parts = {"state": state, "engine": engine, "soar": soar_engine, "sim": sim, "normalizer": norm}
    if serve:
        import uvicorn
        app = dashboard.create_app(bus, state)
        port = port or config.DASHBOARD_PORT
        print(f"\n  eBPF SOC dashboard ->  http://localhost:{port}\n")
        uvicorn.run(app, host=config.DASHBOARD_HOST, port=port, log_level="warning")
    return bus, parts


def main():
    ap = argparse.ArgumentParser(description="eBPF Autonomous Threat Hunting SOC (all-in-one)")
    ap.add_argument("--eps", type=float, default=config.BACKGROUND_EPS, help="benign events/second")
    ap.add_argument("--port", type=int, default=config.DASHBOARD_PORT)
    ap.add_argument("--kafka", action="store_true", help="use Kafka at $KAFKA_BOOTSTRAP instead of memory bus")
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)-14s %(levelname)-7s %(message)s")
    start_pipeline(eps=args.eps, serve=True, bus_kind="kafka" if args.kafka else "memory", port=args.port)


if __name__ == "__main__":
    main()
